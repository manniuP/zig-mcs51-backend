//! rtlib 的反例：**运行期**移位次数不能套固定模板。
//!
//! 模板把次数放 r0、用 `djnz` 循环，而 `djnz` 是先减后判——次数 0 会转 256 次。
//! 所以常量次数才走模板，运行期次数必须回到「每轮 1 位」的循环内联。
//!
//! 这个文件单独一份，是为了让 mcs2.py 的 `want_no_rt` 断言能只看本单元产物：
//! 和 `sar32` 放在一起时，同一份汇编里已经有了模板调用，断言会误判。

// 0xCAFEBABE >> 11 = 0xFFF95FD7
export fn sar32v(x: i32, n: u8) i32 {
    return x >> @truncate(n);
}
